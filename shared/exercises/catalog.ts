import type { CvExerciseConfig, ExerciseDefinition } from '../schemas/exercise.ts';
import { curlCv, forExercise, lungeCv, pressCv } from './cvConfigs.ts';

/**
 * Non-CV exercises (cvSupport "none"). CV support for lunge, curl, press and
 * push-up is added later. Restriction tags list the user restrictions an
 * exercise conflicts with; they describe movements, not medical safety.
 */

type CatalogInput = Pick<
  ExerciseDefinition,
  'id' | 'name' | 'movementPattern' | 'targetMuscles' | 'difficulty' | 'instructions' | 'applicableGoals'
> &
  Partial<ExerciseDefinition>;

const ALL_LEVELS: ExerciseDefinition['applicableLevels'] = ['beginner', 'intermediate', 'advanced'];
const NOT_BEGINNER: ExerciseDefinition['applicableLevels'] = ['intermediate', 'advanced'];
const STRENGTH_GOALS: ExerciseDefinition['applicableGoals'] = ['strength', 'muscle_building', 'general_fitness'];
const CONDITIONING_GOALS: ExerciseDefinition['applicableGoals'] = ['endurance', 'weight_management', 'general_fitness'];

/** Attach a CV configuration (the config's id is set to the exercise id). */
const withCv = (config: CvExerciseConfig, id: string) => ({
  cvSupport: 'rep_counting_and_form' as const,
  cv: forExercise(config, id),
});

function exercise(input: CatalogInput): ExerciseDefinition {
  return {
    requiredEquipment: [],
    roles: ['main'],
    targetType: 'reps',
    secondsPerRep: 3,
    perSide: false,
    minSpace: 'small',
    demoUrl: null,
    applicableLevels: ALL_LEVELS,
    restrictionTags: [],
    cvSupport: 'none',
    cv: null,
    ...input,
  };
}

